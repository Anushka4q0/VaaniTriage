def confirmation_text(incident_id: int, severity: str, language_code: str) -> str:
    lang = normalize_language_code(language_code) or language_code
    template = phrase(CONFIRMATION, lang)
    severity_word = SEVERITY_WORDS.get(lang, SEVERITY_WORDS["en-IN"]).get(severity, severity)
    return template.format(digits=spell_number(incident_id, lang), severity=severity_word)


def follow_up_speech(question_ids: list[str], language_code: str) -> str:
    lang = normalize_language_code(language_code) or language_code
    intro = phrase(FOLLOW_UP_INTRO, lang)
    questions = [follow_up_text(question_id, lang) for question_id in question_ids]
    return " ".join([intro, *questions])


def suggestion_speech(steps: list[str], language_code: str = "en-IN") -> str:
    lang = normalize_language_code(language_code) or language_code
    intro = phrase(SUGGESTION_INTROS, lang)
    prefix_tmpl = phrase(STEP_PREFIX, lang)
    digits_map = DIGIT_WORDS.get(lang, DIGIT_WORDS["en-IN"])
    spoken = [intro]
    for index, step in enumerate(steps[:3], start=1):
        num_str = digits_map[index] if index < len(digits_map) else str(index)
        prefix = prefix_tmpl.format(index=num_str)
        spoken.append(f"{prefix} {' '.join(step.split())}")
    return " ".join(spoken)


def incident_summary_speech(incident_id: int, title: str, severity: str, status: str, language_code: str) -> str:
    lang = normalize_language_code(language_code) or language_code
    template = phrase(SUMMARY_TEMPLATES, lang)
    severity_word = SEVERITY_WORDS.get(lang, SEVERITY_WORDS["en-IN"]).get(severity, severity)
    status_word = STATUS_WORDS.get(status, {}).get(lang, status)
    safe_title = " ".join((title or "").split())[:120]
    return template.format(
        digits=spell_number(incident_id, lang),
        title=safe_title,
        severity=severity_word,
        status=status_word,
    )


