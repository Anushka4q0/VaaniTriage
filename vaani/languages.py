def is_timbre_supported(language_code: str | None) -> bool:
    if not language_code:
        return False
    norm = normalize_language_code(language_code)
    return bool(norm and norm in TIMBRE_VOICES)


def voice_for_language(language_code: str | None) -> tuple[str, str, str]:
    norm = normalize_language_code(language_code) or language_code or ""
    voice, language = TIMBRE_VOICES.get(norm, TIMBRE_VOICES["en-IN"])
    return voice, language, TTS_MODEL


def normalize_language_code(code: str | None) -> str | None:
    if not code:
        return None
    cleaned = code.strip()
    if cleaned in TIMBRE_VOICES:
        return cleaned
    lowered = cleaned.lower()
    if lowered in TIMBRE_VOICES:
        return lowered
    return LANGUAGE_CODE_ALIASES.get(lowered, None)


def language_from_script(text: str) -> str | None:
    counts = {code: len(re.findall(pattern, text or "")) for code, pattern in SCRIPT_PATTERNS}
    best = max(counts, key=counts.get)
    if counts[best] == 0:
        return None
    return best


def language_for_speech(detected: str | None, text: str) -> str:
    """Prefer Prisma's detected_language_code. Fall back to script or Hinglish detection."""
    norm = normalize_language_code(detected)
    if norm and norm in TIMBRE_VOICES:
        return norm
    script_language = language_from_script(text or "")
    if script_language:
        return script_language
    lowered = (text or "").lower()
    if re.search(r"[a-z]", lowered) and re.search(r"\b(hai|nahi|nahin|mera|kya|hoga)\b", lowered):
        return "hi-en"
    return "en-IN"


def spell_number(value: int, language_code: str) -> str:
    lang = normalize_language_code(language_code) or language_code
    words = DIGIT_WORDS.get(lang, DIGIT_WORDS["en-IN"])
    digits = [words[int(ch)] for ch in str(abs(int(value)))]
    return " ".join(digits)


def phrase(table: dict[str, str], language_code: str) -> str:
    lang = normalize_language_code(language_code) or language_code
    return table.get(lang) or table.get("en-IN") or ""


def follow_up_text(question_id: str, language_code: str) -> str:
    questions = FOLLOW_UP_QUESTIONS.get(question_id, FOLLOW_UP_QUESTIONS["details"])
    lang = normalize_language_code(language_code) or language_code
    return questions.get(lang) or questions["en-IN"]


def severity_reason_text(severity: str, language_code: str) -> str:
    table = SEVERITY_REASONS.get(severity, SEVERITY_REASONS["Medium"])
    lang = normalize_language_code(language_code) or language_code
